/** Decodes the mask: 255 for land, 0 for water. */
export function landMask(): Uint8Array {
  const bytes = Uint8Array.from(atob(RUNS), (c) => c.charCodeAt(0));
  const out = new Uint8Array(LAND_W * LAND_H);
  let p = 0;
  let i = 0;
  while (p < bytes.length && i < out.length) {
    const rowEnd = i - (i % LAND_W) + LAND_W;
    let land = false;
    while (i < rowEnd) {
      let run = 0;
      let shift = 0;
      let b: number;
      do { b = bytes[p++]!; run |= (b & 0x7f) << shift; shift += 7; } while (b & 0x80);
      if (land) out.fill(255, i, i + run);
      i += run;
      land = !land;
    }
  }
  return out;
}
